"""Split assignment CSV export.

Spreadsheet formula injection
-----------------------------
A CSV cell beginning with ``=``, ``+``, ``-`` or ``@`` (or a tab / carriage
return) can be executed as a formula by spreadsheet software when the file is
opened. Since row content is user-supplied data, exported text cells are prefixed
with a single quote ``'`` when they start with one of those characters.

This changes the *export only*. The stored dataset, the audit and the JSON report
are never modified, and the transformation is documented in the API response
headers and in the UI so that nobody mistakes the quote for part of the value.
Numeric-looking cells are left untouched so that row identifiers and counts keep
their meaning.
"""

from __future__ import annotations

import csv
import io
from collections.abc import Iterable

from app.audit.types import SplitAssignment

DANGEROUS_PREFIXES = ("=", "+", "-", "@", "\t", "\r")

EXPORT_SANITIZATION_NOTE = (
    "Text cells beginning with =, +, -, @, tab or carriage return are prefixed with a single "
    "quote to prevent spreadsheet formula injection. The stored dataset and the JSON report are "
    "unaffected."
)


def sanitize_csv_cell(value: str) -> str:
    """Prefix a leading formula trigger with a quote; leave other values alone."""
    if value and value[0] in DANGEROUS_PREFIXES:
        return "'" + value
    return value


def build_assignment_csv(assignment: SplitAssignment, *, include_header_note: bool = False) -> str:
    """Return the CSV text for one split assignment.

    Columns are ``row_id``, ``split``, ``strategy``, ``achieved_test_fraction`` and ``seed``.
    Row identifiers are generated by SplitScope, so they are stable and safe;
    the sanitisation applies to any value that could originate from the user's
    file.
    """
    buffer = io.StringIO()
    writer = csv.writer(buffer, lineterminator="\n")
    if include_header_note:
        writer.writerow([f"# {EXPORT_SANITIZATION_NOTE}"])
    writer.writerow(["row_id", "split", "strategy", "strategy_kind", "achieved_test_fraction", "seed"])
    summary = assignment.summary
    for row_id in assignment.train_row_ids:
        writer.writerow(
            [
                sanitize_csv_cell(row_id),
                "train",
                sanitize_csv_cell(summary.label),
                summary.kind,
                f"{summary.achieved_test_fraction:.6f}",
                "" if summary.seed is None else summary.seed,
            ]
        )
    for row_id in assignment.test_row_ids:
        writer.writerow(
            [
                sanitize_csv_cell(row_id),
                "test",
                sanitize_csv_cell(summary.label),
                summary.kind,
                f"{summary.achieved_test_fraction:.6f}",
                "" if summary.seed is None else summary.seed,
            ]
        )
    return buffer.getvalue()


def iter_assignment_rows(assignment: SplitAssignment) -> Iterable[tuple[str, str]]:
    for row_id in assignment.train_row_ids:
        yield row_id, "train"
    for row_id in assignment.test_row_ids:
        yield row_id, "test"


__all__ = [
    "DANGEROUS_PREFIXES",
    "EXPORT_SANITIZATION_NOTE",
    "build_assignment_csv",
    "iter_assignment_rows",
    "sanitize_csv_cell",
]
